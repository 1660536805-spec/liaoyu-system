from PIL import Image
import os, numpy as np

REF = "/Users/leo/Desktop/ui/最终版"
P = lambda n: os.path.join(REF, n)

def sample(name, pts):
    im = Image.open(P(name)).convert("RGB")
    a = np.asarray(im)
    print(f"\n=== {name} ===")
    for label, x, y in pts:
        patch = a[y-4:y+5, x-4:x+5].reshape(-1, 3)
        med = np.median(patch, axis=0).astype(int)
        print(f"  {label:26s} ({x:4d},{y:4d})  #{med[0]:02X}{med[1]:02X}{med[2]:02X}  rgb{tuple(med)}")

